-- 背景:
--   ことづて機能はアプリ側から削除済み（PR #484）だが、kotodutes テーブルと
--   投稿データ（visitor_key 付きのメッセージ）はDBに残ったままだった。
--   利用目的が終わったデータを保持し続けるのはデータ最小化の原則に反する。
--
-- 対策:
--   テーブルごと削除する（RLSポリシー・インデックス・FKも同時に消える）。
--   reports テーブルの過去の通報行（target_type = 'kotodute'）は
--   通報対応の記録として残す。

drop table if exists public.kotodutes cascade;

